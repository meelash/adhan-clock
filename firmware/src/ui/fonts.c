#define SMALL_FONT_FIRST 32
#define SMALL_FONT_LAST  126
#define SMALL_FONT_COUNT (SMALL_FONT_LAST - SMALL_FONT_FIRST + 1)

const uint8_t *font_small_glyph(char c) {
    int idx = (int)(unsigned char)c - SMALL_FONT_FIRST;
    if (idx < 0 || idx >= SMALL_FONT_COUNT) return NULL;
    return small_font_data[idx];
}

/* ── Drawing functions ──────────────────────────────────────────────────── */

int font_draw_large(int x, int y, char c, uint16_t colour) {
    const uint16_t *glyph = font_large_glyph(c);
    if (!glyph) return 0;

    int width = (c == ':') ? FONT_LARGE_COLON_W : FONT_LARGE_W;

    for (int row = 0; row < FONT_LARGE_H; row++) {
        uint16_t bits = glyph[row];
        for (int col = 0; col < width; col++) {
            if (bits & (1 << (width - 1 - col))) {
                hub75_set_pixel(x + col, y + row, colour);
            }
        }
    }
    return width + 1; /* 1px inter-character gap */
}

int font_draw_small(int x, int y, char c, uint16_t colour) {
    const uint8_t *glyph = font_small_glyph(c);
    if (!glyph) return FONT_SMALL_W + 1;

    for (int row = 0; row < FONT_SMALL_H; row++) {
        uint8_t bits = glyph[row];
        for (int col = 0; col < FONT_SMALL_W; col++) {
            if (bits & (1 << (FONT_SMALL_W - 1 - col))) {
                hub75_set_pixel(x + col, y + row, colour);
            }
        }
    }
    return FONT_SMALL_W + 1; /* 1px inter-character gap */
}

int font_draw_string(int x, int y, const char *str, uint16_t colour) {
    int cx = x;
    while (*str) {
        cx += font_draw_small(cx, y, *str, colour);
        str++;
    }
    return cx - x;
}

int font_draw_large_string(int x, int y, const char *str, uint16_t colour) {
    int cx = x;
    while (*str) {
        cx += font_draw_large(cx, y, *str, colour);
        str++;
    }
    return cx - x;
}

int font_measure_string(const char *str) {
    int w = 0;
    while (*str) { w += FONT_SMALL_W + 1; str++; }
    if (w > 0) w--; /* remove trailing gap */
    return w;
}

int font_measure_large_string(const char *str) {
    int w = 0;
    while (*str) {
        w += (*str == ':' ? FONT_LARGE_COLON_W : FONT_LARGE_W) + 1;
        str++;
    }
    if (w > 0) w--;
    return w;
}
